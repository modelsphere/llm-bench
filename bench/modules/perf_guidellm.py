"""
GuideLLM Real-World Throughput & Latency Benchmark

Sends concurrent users through a real or synthetic dataset via GuideLLM's
Poisson-arrival scheduler and returns raw performance metrics.

Score and pass/fail are NOT computed here — the platform evaluator uses
per-benchmark MetricConfig rules (stored in BenchmarkModule.metric_configs_json).

Default evaluation (default_metric_configs):
  Score: 0.5 × (input_tps / baseline) + 0.5 × (output_tps / baseline)  [ratio, uncapped]
  Redlines: TTFT/TPOT/ITL P99 & P50 max thresholds, uptime min threshold
            (P90 is reported too, but display-only)

Load is generated by guidellm: Poisson arrivals, with an optional ShareGPT
dataset file; without one it sends random tokens of the requested shape.
"""
from __future__ import annotations

import os
import sys
import re
import threading
import time
from typing import Optional

from pydantic import BaseModel, Field

from bench.modules.base import (
    AllRequestsFailed, BenchmarkTimeout, EndpointConfig, MetricConfig, MetricDescriptor,
    ModuleResult, ProgressCallback, TestModule, _noop_progress,
)
from utils.logger import logger


class PerfGuidellmParams(BaseModel):
    backend: str = Field(
        default="guidellm",
        description="Load backend. Only 'guidellm' is supported.",
    )
    concurrency: int = Field(default=5, ge=1, le=4096, description="Concurrent users / concurrency level")
    input_tokens: int = Field(default=50000, ge=1, le=1_000_000_000, description="Input tokens per request")
    output_tokens: int = Field(default=1500, ge=1, description="Max output tokens per request")
    max_seconds: float = Field(default=300.0, ge=1.0, le=604800.0, description="Test duration in seconds")
    request_timeout: float = Field(default=120.0, ge=1.0, le=86400.0, description="Per-request timeout in seconds")
    warmup_seconds: float = Field(default=30.0, ge=0.0, le=86400.0, description="[guidellm] Warmup duration in seconds")
    dataset_path: Optional[str] = Field(
        default=None,
        description="[guidellm] Path to ShareGPT-format dataset file. Leave blank to use random tokens."
    )
    processor_path: Optional[str] = Field(
        default=None,
        description=(
            "[guidellm] Tokenizer/processor directory for accurate token counts. "
            "Relative paths resolve against the project root (e.g. "
            "'/models/Qwen3-8B' or a HF repo id). Leave blank to use the built-in "
            "default or the PROCESSOR_PATH env var."
        ),
    )


# Card baseline for the display-only card-normalized TPM metrics
# (`*_tpm_card_norm`, computed by the platform worker): throughput is rescaled
# as if the endpoint ran on this many cards.
CARD_NORM_BASELINE = 8


class _GuidellmBudgetMixin:
    """Declares the guidellm deadline as this module's own wall-clock bound.

    Without this the worker's backstop would be sized off `params.max_seconds`,
    which for guidellm is the duration of ONE concurrency level and excludes
    warmup and the in-flight drain — so the backstop could land *below* the
    deadline guidellm itself enforces and abort healthy runs. Reuses the exact
    function the run path uses, so the two can never drift.
    """

    @classmethod
    def _budget_rates(cls, params) -> list:
        raise NotImplementedError

    @classmethod
    def time_budget_seconds(cls, params) -> "float | None":
        try:
            return compute_guidellm_run_timeout(
                cls._budget_rates(params),
                getattr(params, "warmup_seconds", 0.0),
                getattr(params, "max_seconds", 0.0),
                getattr(params, "request_timeout", 0.0),
            )
        except Exception:
            return None


