    def run(
        self,
        endpoint: EndpointConfig,
        params: BaseModel,
        output_dir: str,
        progress_cb: ProgressCallback = _noop_progress,
        cancel_event=None,
    ) -> ModuleResult:
        p: PerfGuidellmParams = params  # type: ignore[assignment]
        os.makedirs(output_dir, exist_ok=True)

