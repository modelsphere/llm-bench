# Matches RealWorldTest's per-level suffix (`ttft_p99_ms_c8`). Kept local rather
# than imported from perf_guidellm_sweep, which imports *from* this module.
_LEVEL_SUFFIX_RE = re.compile(r"_c(\d+)$")


def _promote_single_level_keys(metrics: dict) -> None:
    """Expose this run's one concurrency level under flat, unsuffixed keys.

    RealWorldTest emits every stat suffixed with the level (`measured_requests_c8`)
    and promotes only a hardcoded subset to flat names, so stats it does not list
    — `duration_seconds`, `measured_requests`, the TPS percentiles — had no
    unsuffixed key here and could not be named in a MetricConfig. The sweep has
    them because its `_promote_canonical` copies a whole level wholesale; this is
    the same idea for the single level this module runs.

    The suffixed keys stay: they are this module's long-standing output contract.
    Promotion never overwrites — where RealWorldTest already chose a flat value it
    wins, though with one level the two are the same number by construction.
    """
    for key, val in list(metrics.items()):
        m = _LEVEL_SUFFIX_RE.search(key)
        if m:
            metrics.setdefault(key[: m.start()], val)


def _add_flat_request_output_tps(metrics: dict, concurrency: int) -> None:
    """Add the per-request (single-stream) output TPS: aggregate output_tps
    divided by the concurrency that produced it.

    Mirrors perf_guidellm_sweep's `request_output_tps`, so the two modules report
    the same number under the same key and a benchmark can gate on it either way.
    The sweep's version walks its nested per-level dicts, dividing each level's
    aggregate by that level; this module runs exactly one level, so it writes the
    flat top-level key directly — hence the different function name.

    Prefers guidellm's reported level over the requested concurrency so the
    numerator and denominator always describe the same run, falling back to the
    requested level when nothing was reported.
    """
    try:
        level = float(metrics.get("reported_concurrency") or concurrency)
        metrics["request_output_tps"] = float(metrics["output_tps"]) / level
    except (KeyError, TypeError, ValueError, ZeroDivisionError):
        return


# Runaway guard for the guidellm run. guidellm's own max_seconds bounds only its
# REQUEST phase — a run was observed completing that phase normally (full
# duration, every request 200) and then deadlocking in teardown, pinning the
# worker for 7+ hours with its forked processes parked forever. These size a
# hard external deadline: whichever of (expected x slack) or (expected + headroom)
# is larger, so short runs still get generous absolute room.
GUIDELLM_TIMEOUT_SLACK = float(os.getenv("GUIDELLM_TIMEOUT_SLACK", "3.0"))
GUIDELLM_TIMEOUT_HEADROOM_SECONDS = float(os.getenv("GUIDELLM_TIMEOUT_HEADROOM_SECONDS", "1800"))


def compute_guidellm_run_timeout(
    rates: list, warmup_seconds: float, max_seconds: float, request_timeout: float
) -> float:
    """Hard wall-clock budget for one guidellm invocation.

    Shared by the run path and the modules' ``time_budget_seconds`` so the
    worker's backstop is sized off the SAME number this run will actually
    enforce, instead of a second formula that could drift below it and abort
    healthy runs.

    Each concurrency level runs sequentially for (warmup + max_seconds), and when
    a level's duration expires guidellm still drains the requests already in
    flight — up to request_timeout per level, which the schema allows to be
    hours. Hence the explicit drain term.
    """
    total_seconds = len(rates) * (float(warmup_seconds) + float(max_seconds))
    return max(
        total_seconds * GUIDELLM_TIMEOUT_SLACK,
        total_seconds + GUIDELLM_TIMEOUT_HEADROOM_SECONDS,
    ) + len(rates) * float(request_timeout)


def run_guidellm_load(
    endpoint,
    *,
    rates: list,
    input_tokens: int,
    output_tokens: int,
    max_seconds: float,
    request_timeout: float,
    warmup_seconds: float,
    dataset_path: Optional[str],
    processor_path: Optional[str],
    output_dir: str,
    progress_cb: ProgressCallback,
    cancel_event,
    log_tag: str = "perf_guidellm",
    requests_per_concurrency: Optional[int] = None,
    random_seed: Optional[int] = None,
    warmup_fraction: Optional[float] = None,
    cooldown_fraction: Optional[float] = None,
):
    """Shared guidellm execution path for perf_guidellm and perf_guidellm_sweep.

    Runs guidellm's concurrent profile at each concurrency level in `rates`
    (sequentially, `max_seconds` each) and returns the merged metrics dict from
    RealWorldTest (per-level `*_c{N}` keys + canonical top-level keys), with
    HTTP status counts folded in. Returns None on failure.

    `requests_per_concurrency` switches levels to count-limited sampling: level
    c stops after c × that many requests, with `max_seconds` demoted to a
    safety cap (whichever fires first). None = duration-limited (legacy).

    `random_seed` seeds guidellm's synthetic prompt generator; None keeps the
    BenchConfig default. The same seed reproduces the same prompt sequence run
    after run, so callers that run repeatedly against one endpoint (the auto
    search) vary it to keep a server-side prefix cache from flattering them.

    `warmup_fraction` / `cooldown_fraction` are the shares of a count-limited
    level's requests discarded at its start and end (None = RealWorldTest's
    defaults, 10% / 5%). Duration-limited levels ignore them.
    """
    # REALWORLD_TEST_* env vars are read inside RealWorldTest.__init__ at
    # construction time (not module-import time), so setting them here
    # works correctly across submissions even in long-lived workers.
    # dataset_path and rates are passed explicitly because env values were
    # previously captured at module-import in b_realworld.py — see that
    # file's docstring.
    env_map = {
        "REALWORLD_TEST_PROMPT_TOKENS": str(input_tokens),
        "REALWORLD_TEST_OUTPUT_TOKENS": str(output_tokens),
        "REALWORLD_TEST_MAX_SECONDS":   str(int(max_seconds)),
        "REALWORLD_TEST_TIMEOUT":       str(int(request_timeout)),
        "REALWORLD_TEST_WARMUP":        str(warmup_seconds),
    }

    from utils.logger import HTTPX_STATUS_DUMP_DIR_ENV, read_httpx_status_dump
    status_dump_dir = os.path.join(output_dir, "_httpx_status")
    env_map[HTTPX_STATUS_DUMP_DIR_ENV] = status_dump_dir

    old_env = {k: os.environ.get(k) for k in env_map}
    for k, v in env_map.items():
        os.environ[k] = v

    # guidellm wall-time ≈ (warmup + max_seconds) per concurrency level. Use
    # this for the elapsed/total progress display since the upstream API
    # exposes no real progress hook.
    total_seconds = len(rates) * (float(warmup_seconds) + float(max_seconds))
    # Hard wall-clock budget. guidellm's own max_seconds only bounds its request
    # phase; a run has been seen finish that phase normally and then deadlock in
    # teardown, pinning the worker for hours with no way out. So bound the whole
    # thing externally, with generous slack for warmup, prefill on long prompts,
    # and aggregation — this is a runaway guard, not a schedule.
    run_timeout = compute_guidellm_run_timeout(
        rates, warmup_seconds, max_seconds, request_timeout
    )
    stop_progress = _start_elapsed_progress(progress_cb, total_seconds=total_seconds)
    try:
        from bench.tests.b_realworld import RealWorldTest
        test = RealWorldTest(
            endpoint.api_url, endpoint.model, endpoint.api_key, output_dir,
            dataset_path=dataset_path or None,
            processor_path=processor_path or None,
            rates=rates,
            requests_per_concurrency=requests_per_concurrency,
            random_seed=random_seed,
            warmup_fraction=warmup_fraction,
            cooldown_fraction=cooldown_fraction,
        )
        # Hard deadline for the underlying guidellm call (see run_timeout above).
        test.run_timeout = run_timeout
        logger.info(
            "[%s] guidellm budget: expected ~%.0fs (%d level(s) x (%.0fs warmup + %.0fs run)), "
            "hard timeout %.0fs (runaway guard: %sx slack, +%.0fs headroom, "
            "+%d x %.0fs in-flight drain)",
            log_tag, total_seconds, len(rates), warmup_seconds, max_seconds,
            run_timeout, GUIDELLM_TIMEOUT_SLACK, GUIDELLM_TIMEOUT_HEADROOM_SECONDS,
            len(rates), request_timeout,
        )
        result = test.run(cancel_event=cancel_event)
        progress_cb(0.9, "GuideLLM run complete, aggregating metrics")
        metrics = result.metrics if result.metrics else None
        if metrics is not None:
            # NOTE: status counts accumulate over the whole guidellm run — for a
            # multi-level sweep they are totals across all levels, not per-level.
            status_counts = read_httpx_status_dump(status_dump_dir)
            if status_counts:
                total = sum(status_counts.values())
                breakdown = " ".join(f"{c}={n}" for c, n in sorted(status_counts.items()))
                logger.info("[%s] HTTP status totals: total=%d %s", log_tag, total, breakdown)
                for code, n in status_counts.items():
                    metrics[f"http_status_{code}"] = float(n)
            elif sys.platform == "darwin":
                # guidellm >= 0.7.2 forces `spawn` for its workers on macOS, and a
                # spawned worker does not inherit the httpx counting filter
                # (utils.logger) unless its parent's __main__ happens to import it.
                # Linux — every deployment — uses `fork` and counts normally. The
                # metrics are omitted rather than reported as zero.
                logger.info("[%s] http_status_* unavailable on macOS (guidellm spawns "
                            "its workers there); counted on Linux", log_tag)
            else:
                logger.warning("[%s] no httpx status dumps found in %s", log_tag, status_dump_dir)
        return metrics
    except AllRequestsFailed:
        # Carries the concrete per-request reason; let the worker record it as
        # the run's error instead of collapsing it to "produced no metrics".
        raise
    except BenchmarkTimeout:
        # Same reasoning: "exceeded its Ns budget" is the whole diagnosis for a
        # wedged run, and is far more actionable than "produced no metrics".
        raise
    except Exception:
        from traceback import format_exc
        logger.error("[%s] guidellm run failed: %s", log_tag, format_exc())
        return None
    finally:
        stop_progress()
        for k, old_v in old_env.items():
            if old_v is None:
                os.environ.pop(k, None)
            else:
                os.environ[k] = old_v


_PROGRESS_TICK_SECONDS = 30.0
# Map elapsed/total ∈ [0, 1] onto a [floor, ceiling] band so progress always lies
# between the module's initial "0.05 starting" tick and the post-run "0.9 done"
# tick. This keeps the bar monotonic and leaves room for the aggregation step.
_PROGRESS_FLOOR = 0.10
_PROGRESS_CEILING = 0.85


def _start_elapsed_progress(progress_cb, total_seconds: float):
    """Spawn a daemon thread that emits `elapsed/total` progress every few seconds.

    Returns a stop() callable. Always call stop() in a `finally` block. The
    progress_cb may raise (e.g. SubmissionCancelled) — that's caught and
    logged so the watcher thread always exits cleanly. The blocking benchmark
    call itself is what observes cancellation.
    """
    stop_event = threading.Event()

    def _loop() -> None:
        t0 = time.monotonic()
        while not stop_event.wait(timeout=_PROGRESS_TICK_SECONDS):
            elapsed = time.monotonic() - t0
            if total_seconds > 0:
                frac = min(elapsed / total_seconds, 1.0)
            else:
                frac = 0.0
            scaled = _PROGRESS_FLOOR + frac * (_PROGRESS_CEILING - _PROGRESS_FLOOR)
            msg = f"Running benchmark — {int(elapsed)}s / {int(total_seconds)}s elapsed"
            try:
                progress_cb(scaled, msg)
            except Exception:
                # The platform's progress_cb raises SubmissionCancelled on cancel;
                # let the main thread observe that via its own checks.
                return

    thread = threading.Thread(target=_loop, daemon=True, name="guidellm-progress")
    thread.start()

    def stop() -> None:
        stop_event.set()
        thread.join(timeout=2)

    return stop
